export function featuresByGroup(lang: 'en' | 'hi'): { group: string; items: SiteFeature[] }[] {
  const map = new Map<string, SiteFeature[]>()
  for (const f of SITE_FEATURES) {
    const g = lang === 'hi' ? f.groupHi : f.groupEn
    const list = map.get(g) ?? []
    list.push(f)
    map.set(g, list)
  }
  return [...map.entries()].map(([group, items]) => ({ group, items }))
}
